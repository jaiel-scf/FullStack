-- Executar no SQL Editor do Supabase antes de publicar o novo backend.
-- Preserva integralmente as movimentacoes e requisicoes anteriores.
CREATE TABLE IF NOT EXISTS public.requisicao_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisicao_id BIGINT NOT NULL REFERENCES public.movimentacoes(id) ON DELETE RESTRICT,
    produto_id BIGINT NOT NULL REFERENCES public.produtos(id) ON DELETE RESTRICT,
    quantidade BIGINT NOT NULL CHECK (quantidade > 0),
    CONSTRAINT uq_requisicao_produto UNIQUE (requisicao_id, produto_id)
);
CREATE INDEX IF NOT EXISTS idx_requisicao_itens_requisicao
    ON public.requisicao_itens(requisicao_id);
-- Requisicoes antigas permanecem com produto_id/quantidade em movimentacoes;
-- o backend fornece esses campos como um item virtual ao listar.
